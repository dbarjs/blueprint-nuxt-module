export function cssTemplate(sources: string[]): string {
  return [
    '@import "tailwindcss";',
    '@import "@nuxt/ui";',
    ...sources.map(source => `@source ${JSON.stringify(source)};`),
    '',
  ].join('\n')
}

export function contentConfigTemplate(contentDir: string): string {
  return [
    '// Generated by blueprint-nuxt-module — registers the `blueprints` data collection.',
    'import { defineCollection, defineContentConfig, z } from \'@nuxt/content\'',
    '',
    'export default defineContentConfig({',
    '  collections: {',
    '    blueprints: defineCollection({',
    '      type: \'data\',',
    `      source: { include: '**/*.json', cwd: ${JSON.stringify(contentDir)} },`,
    '      schema: z.object({',
    '        name: z.string().optional(),',
    '        id: z.string().optional(),',
    '        from: z.object({}).passthrough().optional(),',
    '        content: z.object({}).passthrough(),',
    '      }),',
    '    }),',
    '  },',
    '})',
    '',
  ].join('\n')
}
