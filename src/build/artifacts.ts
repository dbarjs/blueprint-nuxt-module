/**
 * Generated artifacts in `.nuxt/blueprint/`: lazy registry, manifest and
 * the JSON Schema of the document format (for editor IntelliSense).
 */
import { BASE_VOCABULARY } from '../runtime/engine/registry'

export interface RegistryLayers {
  base: string[]
  nuxtUi: string[]
  app: string[]
  /** Runtime components shipped by the module (back the base names). */
  runtime: string[]
}

export interface ComponentInfo {
  pascalName: string
  filePath: string
  layer: 'nuxtUi' | 'app' | 'runtime'
}

export function registryTemplate(components: ComponentInfo[]): string {
  const names = [...new Set(components.map(component => component.pascalName))].sort()
  const exports = names.map(name => `  ${name}: Lazy${name},`)
  const aliases = Object.entries(BASE_VOCABULARY).map(([name, entry]) => `  ${name}: ${JSON.stringify(entry.to)},`)
  return [
    '// Generated by blueprint-nuxt-module — lazy component registry.',
    `import { ${names.map(name => `Lazy${name}`).join(', ')} } from '#components'`,
    '',
    'export const registry = {',
    ...exports,
    '}',
    '',
    '/** Base vocabulary name → Vue component name. */',
    'export const aliases = {',
    ...aliases,
    '}',
    '',
    `export const layers = ${JSON.stringify(layersOf(components), null, 2)}`,
    '',
    'export function resolveRegistered(name) {',
    '  const target = aliases[name] || name',
    '  return registry[target]',
    '}',
    '',
  ].join('\n')
}

export function layersOf(components: ComponentInfo[]): RegistryLayers {
  const pick = (layer: ComponentInfo['layer']) => [...new Set(components.filter(component => component.layer === layer).map(component => component.pascalName))].sort()
  return {
    base: Object.keys(BASE_VOCABULARY),
    nuxtUi: pick('nuxtUi'),
    app: pick('app'),
    runtime: pick('runtime'),
  }
}

export function manifestTemplate(components: ComponentInfo[], version: string): string {
  const layers = layersOf(components)
  const manifest = {
    vocabulary: 'blueprint-nuxt-module',
    version,
    layers: {
      base: Object.fromEntries(Object.entries(BASE_VOCABULARY).map(([name, entry]) => [name, {
        description: entry.description,
        materializedBy: entry.to,
        props: entry.props || {},
        slots: entry.slots || [],
        events: entry.events || [],
      }])),
      nuxtUi: layers.nuxtUi,
      app: layers.app,
    },
    nodeTypes: ['component', 'html', 'text', 'if', 'for', 'template', 'outlet'],
    actionTypes: ['set', 'push', 'remove', 'update', 'increment', 'reset', 'navigate', 'toast', 'if', 'validate', 'submit', 'action', 'sequence', 'log'],
  }
  return JSON.stringify(manifest, null, 2)
}

